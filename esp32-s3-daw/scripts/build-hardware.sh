# Build the hardware firmware (octal PSRAM, Wi-Fi, I2S on GPIO16/6/7) into build-hw/.
# config/local.env (from config/local.env.example) provides Wi-Fi credentials, the admin password
# and pin overrides; it becomes config/sdkconfig.local.defaults (both gitignored).
source "$(dirname "$0")/common.sh"
source_idf
prepare_firmware_inputs
load_local_env
HW_BUILD="${DAW_HW_BUILD:-$ROOT_DIR/build-hw}"
[[ "$HW_BUILD" = /* ]] || HW_BUILD="$ROOT_DIR/$HW_BUILD"
case "${DAW_SAMPLE_RATE:-}" in
  ""|32000|44100|48000) ;;
  *) echo "config/local.env: DAW_SAMPLE_RATE must be 32000, 44100 or 48000" >&2; exit 1 ;;
esac
case "${DAW_FLASH_SIZE_MB:-}" in
  ""|16|32|64|128) ;;
  *) echo "config/local.env: DAW_FLASH_SIZE_MB must be 16, 32, 64 or 128 (the partition map needs at least 16 MB)" >&2; exit 1 ;;
esac
case "${DAW_OCTAL_FLASH:-}" in
  ""|0|1) ;;
  *) echo "config/local.env: DAW_OCTAL_FLASH must be 0 or 1" >&2; exit 1 ;;
esac
# the template's placeholder passwords are public: never build them into a device
for v in DAW_WIFI_PASSWORD DAW_ADMIN_PASSWORD; do
  if [[ "${!v:-}" == change-this-* ]]; then
    echo "config/local.env: $v is still the template's placeholder; set your own (or empty it)" >&2
    exit 1
  fi
done
LOCAL="$ROOT_DIR/config/sdkconfig.local.defaults"
{
  echo "# generated by scripts/build-hardware.sh from config/local.env: do not commit"
  [[ -n "${DAW_SAMPLE_RATE:-}" ]] && echo "CONFIG_DAW_SAMPLE_RATE=$DAW_SAMPLE_RATE"
  [[ -n "${DAW_FLASH_SIZE_MB:-}" ]] && echo "CONFIG_ESPTOOLPY_FLASHSIZE_${DAW_FLASH_SIZE_MB}MB=y"
  # 32 MB and up: a 22 MB sample library (config/partitions-32mb.csv; a table change needs a USB flash)
  [[ "${DAW_FLASH_SIZE_MB:-16}" -ge 32 ]] && echo "CONFIG_PARTITION_TABLE_CUSTOM_FILENAME=\"config/partitions-32mb.csv\""
  if [[ -n "${DAW_OCTAL_FLASH:-}" ]]; then
    if [[ "$DAW_OCTAL_FLASH" == 1 ]]; then
      echo "CONFIG_ESPTOOLPY_OCT_FLASH=y"
      echo "CONFIG_ESPTOOLPY_FLASHMODE_OPI=y"
      echo "CONFIG_ESPTOOLPY_FLASH_SAMPLE_MODE_DTR=y"
      echo "CONFIG_ESPTOOLPY_FLASH_MODE_AUTO_DETECT=n"
    else
      echo "CONFIG_ESPTOOLPY_OCT_FLASH=n"
    fi
  fi
  [[ -n "${DAW_WIFI_MODE:-}" ]] && echo "CONFIG_DAW_WIFI_MODE=\"$DAW_WIFI_MODE\""
  [[ -n "${DAW_WIFI_SSID:-}" ]] && echo "CONFIG_DAW_WIFI_SSID=\"$DAW_WIFI_SSID\""
  [[ -n "${DAW_WIFI_PASSWORD:-}" ]] && echo "CONFIG_DAW_WIFI_PASSWORD=\"$DAW_WIFI_PASSWORD\""
  [[ -n "${DAW_HOSTNAME:-}" ]] && echo "CONFIG_DAW_HOSTNAME=\"$DAW_HOSTNAME\""
  [[ -n "${DAW_ADMIN_PASSWORD:-}" ]] && echo "CONFIG_DAW_ADMIN_PASSWORD=\"$DAW_ADMIN_PASSWORD\""
  [[ -n "${DAW_I2S_BCLK_GPIO:-}" ]] && echo "CONFIG_DAW_I2S_BCLK_GPIO=$DAW_I2S_BCLK_GPIO"
  [[ -n "${DAW_I2S_WS_GPIO:-}" ]] && echo "CONFIG_DAW_I2S_WS_GPIO=$DAW_I2S_WS_GPIO"
  [[ -n "${DAW_I2S_DOUT_GPIO:-}" ]] && echo "CONFIG_DAW_I2S_DOUT_GPIO=$DAW_I2S_DOUT_GPIO"
  true
} > "$LOCAL"
WIFI_PW="${DAW_WIFI_PASSWORD:-}"
if [[ "${DAW_WIFI_MODE:-AP}" != STA && ${#WIFI_PW} -lt 8 ]]; then
  echo "warning: no Wi-Fi password of >= 8 characters in config/local.env: the access point will use a"
  echo "         random password printed on the serial console at every boot"
fi
DEFAULTS="sdkconfig.defaults;config/sdkconfig.hardware.defaults;config/sdkconfig.local.defaults"
refresh_sdkconfig "$HW_BUILD" "$ROOT_DIR/sdkconfig.defaults" "$ROOT_DIR/config/sdkconfig.hardware.defaults" "$LOCAL"
cd "$ROOT_DIR"
idf.py -B "$HW_BUILD" -DIDF_TARGET=esp32s3 -DSDKCONFIG="$HW_BUILD/sdkconfig" -DSDKCONFIG_DEFAULTS="$DEFAULTS" build
grep -E "^CONFIG_DAW_(SAMPLE_RATE|I2S_(BCLK|WS|DOUT)_GPIO)=" "$HW_BUILD/sdkconfig" | sed 's/^/audio: /'
python3 "$ROOT_DIR/scripts/report-size.py" "$HW_BUILD" || true
