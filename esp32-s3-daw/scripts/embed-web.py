"""Embed the browser DAW (web/dist) into the firmware.

Writes components/daw_webserver/generated/web_bundle.bin (every file, gzip-compressed unless that
does not help) and web_index.c (path, MIME type, offset, size). Without web/dist a minimal fallback
page is embedded so the firmware still builds and reports what is missing. /licenses.txt (third-party
notices, scripts/gen-notices.py) is always embedded.
"""
import gzip
import importlib.util
import mimetypes
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(ROOT, "web", "dist")
OUT = os.path.join(ROOT, "components", "daw_webserver", "generated")
MIME = {".js": "text/javascript", ".mjs": "text/javascript", ".css": "text/css", ".html": "text/html; charset=utf-8",
        ".svg": "image/svg+xml", ".json": "application/json", ".png": "image/png", ".ico": "image/x-icon",
        ".woff2": "font/woff2", ".webmanifest": "application/manifest+json", ".txt": "text/plain; charset=utf-8"}
FALLBACK = b"""<!doctype html><meta charset=utf-8><meta name=viewport content="width=device-width">
<title>ESP32-S3 DAW</title><body style="background:#1d2023;color:#ddd;font:15px system-ui;padding:2em">
<h1>ESP32-S3 DAW</h1><p>The firmware runs, but its browser application was not embedded at build
time. Build it with <code>scripts/build-web.sh</code>, then rebuild the firmware.</p>
<p>API: <a style=color:#f90 href=/api/status>/api/status</a></p>"""


def main():
    files = []
    if os.path.isdir(DIST):
        for base, _, names in os.walk(DIST):
            for n in sorted(names):
                full = os.path.join(base, n)
                rel = "/" + os.path.relpath(full, DIST).replace(os.sep, "/")
                if rel.endswith(".map"):
                    continue
                files.append((rel, open(full, "rb").read()))
    if not any(p == "/index.html" for p, _ in files):
        print("embed-web: web/dist/index.html missing: embedding the fallback page", file=sys.stderr)
        files = [("/index.html", FALLBACK)]
    # the firmware's own notices (ESP-IDF and components included), replacing web/dist's host version
    spec = importlib.util.spec_from_file_location("gen_notices", os.path.join(ROOT, "scripts", "gen-notices.py"))
    gn = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gn)
    files = [f for f in files if f[0] != "/licenses.txt"] + [("/licenses.txt", gn.generate("firmware").encode())]
    os.makedirs(OUT, exist_ok=True)
    bundle = bytearray()
    entries = []
    for path, data in sorted(files):
        mime = MIME.get(os.path.splitext(path)[1], mimetypes.guess_type(path)[0] or "application/octet-stream")
        gz = gzip.compress(data, compresslevel=9, mtime=0)
        use = gz if len(gz) < len(data) * 0.95 else data
        entries.append((path, mime, len(bundle), len(use), use is gz))
        bundle += use
        while len(bundle) % 4:
            bundle += b"\0"
    open(os.path.join(OUT, "web_bundle.bin"), "wb").write(bundle)
    with open(os.path.join(OUT, "web_index.c"), "w") as f:
        f.write("/* generated by scripts/embed-web.py */\n#include <stdint.h>\n")
        f.write("struct daw_web_asset { const char *path, *mime; uint32_t offset, size; uint8_t gzip; };\n")
        f.write("const struct daw_web_asset daw_web_assets[] = {\n")
        for p, m, o, s, g in entries:
            f.write(f'    {{"{p}", "{m}", {o}, {s}, {1 if g else 0}}},\n')
        f.write("};\n")
        f.write(f"const uint32_t daw_web_asset_count = {len(entries)};\n")
    print(f"embed-web: {len(entries)} files, {len(bundle)} bytes embedded")


if __name__ == "__main__":
    main()
